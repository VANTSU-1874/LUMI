export function buildHandwrittenTitlePrompts(title: string, background: "WHITE" | "BLACK") {
  const backgroundRule = background === "WHITE"
    ? "背景纯白，字用该风格的原有色。"
    : "背景纯黑，字改为白或近白（或该风格的点缀色），保证可读。";
  return HANDWRITTEN_TITLE_STYLES.map((style) => ({
    styleId: style.id,
    label: style.label,
    prompt: `标题文字：「${title}」（原样渲染，不得改动）\n风格：${style.prompt}\n${backgroundRule}\n${HANDWRITTEN_TITLE_CONTRACT}`,
  }));
}
